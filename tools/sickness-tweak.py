#!/usr/bin/env python3
"""Build and verify the TweakDB overrides that neutralise the Relic sickness.

Design
------
The Relic sickness is a handful of TweakDB status-effect records, not a story
system. Each affected record carries only a fullscreen VFX, a camera-breathing
animation, a fullscreen SFX and a small stamina-regen penalty. Nothing else in
the game depends on that payload -- it is applied by 11 quest call sites (ten
scene nodes in sq032.quest plus one in sq032_sickness.questphase), and all of them
resolve to these same records.

So the override keeps every record and every inheritance edge and only empties
the payload. That is the cheapest correct edit available: no quest-graph changes
and no redscript.

The same intent ships in two forms:

  * ``build`` (patch form) -- full replacements of the two shipped sources,
    applied under tools/redmod/tweaks/ and compiled by a redMod deploy. Kept for
    users who do not run TweakXL.
  * ``yaml``  (drop-in form) -- one r6/tweaks/*.yaml overlay that needs only
    RED4ext + TweakXL, modifies no game file, and uninstalls by deleting the
    file. This is what the Nexus release ships.

Neither form collides with Nexus mod 25974 (which ships quest/scene overrides but
no TweakDB).

Why generate instead of hand-write
----------------------------------
The vanilla sources ship with the game under tools/redmod/tweaks/ and change with
patches. A hand-written copy silently rots the first time CDPR edits a record.
This reads the shipped files, removes exactly the fields we mean to remove, and
prints the diff -- so "what did we actually change" stays answerable after a patch.

Packaging constraint, discovered by deployment
----------------------------------------------
REDmod's tweak compiler merges the base tree and every mod's tweaks/ tree into one
flat compile and REJECTS a redeclared record:

    Line 27: Duplicated group 'JohnnySicknessLow' in package 'BaseStatusEffect'

So a REDmod cannot override an existing vanilla record -- it can only add new ones.
That is why the patch form edits the shipped sources under tools/redmod/tweaks/ instead
of shipping a mods/ folder; the one thing that does live in mods/ is an otherwise empty
marker mod, because `redMod.exe deploy` is a no-op unless at least one mod is deployed.
TweakXL has no redeclaration restriction, so the drop-in form is the release.

Every rule here fails loudly. A removal that matches nothing is an error, never a
silent pass -- an inherited field or a dropped helper record is exactly how the
first two attempts of this tool shipped broken payloads and compile failures.

Usage:
    sickness-tweak.py build       --vanilla-root DIR --out-root DIR [--diff]
    sickness-tweak.py verify      --vanilla-root DIR --override-root DIR
    sickness-tweak.py yaml        --vanilla-root DIR --out FILE
    sickness-tweak.py verify-yaml --vanilla-root DIR --yaml FILE

Read-only with respect to the game: writes nothing unless --out-root/--out is given.
"""

import argparse
import difflib
import pathlib
import re
import sys

# Tokens that must not survive inside a neutralised record.
PAYLOAD_FIELDS = ("VFX", "packages")
FORBIDDEN_IN_TARGET = ("VFX", "packages", "ConstantStatModifier", "StatModifier",
                       "BreathingAnimationEffector", "SFXEffector")
CAMERA_TAG = "CameraAnimation"

# Every record we touch, per shipped source file. Paths are relative to the
# game's tools/redmod/tweaks/ tree.
#
# johnny_sickness.tweak holds the four main records plus the abstract they share.
# quest_custom.tweak holds Phantom Liberty's q304_songbird_relic_shock, which
# INHERITS the same abstract but redefines the whole payload itself -- stripping
# only the first file leaves that one fully intact, which the deploy diff caught.
TARGETS = {
    "base/gameplay/static_data/database/status_effect/johnny_sickness.tweak": {
        "records": ("JohnnySicknessAbstract", "JohnnySicknessLow",
                    "JohnnySicknessMedium", "JohnnySicknessMediumQuest",
                    "JohnnySicknessHeavy"),
        # Only the abstract carries tags, and CameraAnimation is what drives the
        # camera independently of the effectors.
        "strip_tag_from": ("JohnnySicknessAbstract",),
        "strip_tag": CAMERA_TAG,
        "emptied": ("JohnnySicknessLow", "JohnnySicknessMedium",
                    "JohnnySicknessMediumQuest", "JohnnySicknessHeavy"),
    },
    "ep1/gameplay/static_data/database/status_effect/quest_custom.tweak": {
        "records": ("q304_songbird_relic_shock",),
        "strip_tag_from": (),
        "strip_tag": None,
        "emptied": ("q304_songbird_relic_shock",),
    },
}

HEADER = """\
// NoRelicSickness -- neutralises the Relic-sickness status effect.
//
// GENERATED by tools/sickness-tweak.py from the shipped vanilla source.
// Do not hand-edit. After a game patch, regenerate and review the printed diff.
//
// Every record and inheritance edge is preserved, so all quest call sites still
// resolve; only the effect payload is removed. See
// .opencode/specs/002-suppress-relic-sickness/ for the reasoning and
// findings/07-relic-sickness-progression.md for the evidence.

// Comments only. The package/using prologue is copied verbatim from vanilla.
"""


# ---------------------------------------------------------------- parsing ----

RECORD_RE = re.compile(r"^(\w+)\s*:\s*([\w\[\]<> ,]+?)\s*$")


def split_records(text):
    """Yield (name, parent, decl_line, first_body_line, last_body_line)."""
    lines = text.splitlines()
    i = 0
    while i < len(lines):
        m = RECORD_RE.match(lines[i])
        if m and i + 1 < len(lines) and lines[i + 1].strip() == "{":
            name, parent = m.group(1), m.group(2).strip()
            depth = 0
            j = i + 1
            for j in range(i + 1, len(lines)):
                depth += lines[j].count("{") - lines[j].count("}")
                if depth == 0:
                    break
            yield name, parent, i, i + 1, j
            i = j + 1
            continue
        i += 1


def parse(text):
    """Return ({name: (parent, [decl + body lines])}, lines before first record)."""
    lines = text.splitlines()
    records = {name: (parent, lines[head:tail + 1])
               for name, parent, head, _, tail in split_records(text)}
    first = min((h for _, _, h, _, _ in split_records(text)), default=0)
    return records, lines[:first]


def field_span(body, field):
    """Locate a field in a record body as (start, end) line indices.

    A field starts at depth 1 on a line naming it and ends on the line whose
    trailing `;` returns the depth to 1 -- REDscript arrays span many lines.
    """
    depth = 0
    start = None
    for idx, raw in enumerate(body):
        stripped = raw.strip()
        depth += raw.count("{") - raw.count("}")
        if depth == 1 and re.match(rf"^[\w\[\]<> ,]+\s*\b{re.escape(field)}\s*(\+?=)", stripped):
            start = idx
            continue
        if start is not None and depth == 1 and stripped.endswith(";"):
            return start, idx
    return None


# --------------------------------------------------------------- transforms --


def collapse(body):
    """Drop the blank lines a field removal leaves behind."""
    out = []
    for line in body:
        if line.strip() == "" and out and out[-1].strip() in ("{", ""):
            continue
        out.append(line)
    return out


def strip_tag(body, tag, where):
    """Remove one entry from a gameplayTags array. Fails loudly if absent."""
    for i, raw in enumerate(body):
        if re.search(rf'"{tag}"\s*,', raw):
            return body[:i] + [re.sub(rf'"{tag}"\s*,\s*', "", raw)] + body[i + 1:]
    for i, raw in enumerate(body):
        if f'"{tag}"' in raw:
            new = raw.replace(f'"{tag}", ', "").replace(f', "{tag}"', "")
            return body[:i] + [new] + body[i + 1:]
    raise SystemExit(f"build FAILED [{where}]: tag {tag!r} not found -- "
                     f"the shipped source changed shape, review before shipping")


def strip_field(body, field, where, record):
    """Remove a whole field. Fails loudly if absent -- no silent no-ops."""
    span = field_span(body, field)
    if span is None:
        raise SystemExit(f"build FAILED [{where}] {record}: field {field!r} not found -- "
                         f"the shipped source changed shape, review before shipping")
    start, end = span
    while end + 1 < len(body) and body[end + 1].strip() == "":
        end += 1
    return body[:start] + body[end + 1:]


def build_file(vanilla_text, spec, where):
    """Emit a full replacement for one shipped source, payload emptied.

    Every record is carried through in file order, including helper records other
    tweak files link against (SFXEffector, JohnnySicknessUI). Dropping one breaks
    unrelated records elsewhere -- an earlier version emitted only the targeted
    records and compilation then failed on tech_new_perks.tweak and ep1
    quest_custom.tweak, which link to them.
    """
    lines = vanilla_text.splitlines()
    spans = list(split_records(vanilla_text))
    records = {name: lines[head:tail + 1] for name, _, head, _, tail in spans}

    missing = [r for r in spec["records"] if r not in records]
    if missing:
        raise SystemExit(f"build FAILED [{where}]: records absent: {missing}")
    if not spans:
        raise SystemExit(f"build FAILED [{where}]: no records parsed")

    targets = set(spec["records"])
    out = HEADER.rstrip("\n").split("\n") + lines[:spans[0][2]]

    for name, _, _, _, _ in spans:
        raw = records[name]
        if name not in targets:
            out.extend(raw)
        else:
            body = list(raw[1:])
            if name in spec["strip_tag_from"] and spec["strip_tag"]:
                body = strip_tag(body, spec["strip_tag"], where)
            if name in spec["emptied"]:
                for field in PAYLOAD_FIELDS:
                    body = strip_field(body, field, where, name)
                body = collapse(body)
            out.append(raw[0])
            out.extend(body)
        out.append("")

    return "\n".join(out).rstrip() + "\n"


# ---------------------------------------------------------------- yaml ------

# The TweakXL form declares only the properties it changes; the record name and
# every property name below are taken verbatim from the shipped .tweak sources
# (and cross-checked against WolvenKit's gamedataStatusEffect_Record definition,
# where the fields are `gameplayTags`, `packages` and `VFX`).
YAML_HEADER = """\
# NoRelicSickness -- TweakXL overlay that neutralises the Relic-sickness status effect.
#
# GENERATED by tools/sickness-tweak.py from the shipped vanilla sources.
# Do not hand-edit. After a game patch, regenerate with:
#
#   python3 tools/sickness-tweak.py yaml \\
#       --vanilla-root "<Cyberpunk 2077>/tools/redmod/tweaks" \\
#       --out src/no-relic-sickness/tweaks/NoRelicSickness.yaml
#
# Install: copy this file to <Cyberpunk 2077>/r6/tweaks/NoRelicSickness.yaml
# Requires RED4ext and TweakXL. No game file is modified; uninstalling is
# deleting the file.
#
# Every record keeps its name and its inheritance edge, so all 11 quest call
# sites still resolve. Only the effect payload is removed:
#   * VFX[] and packages[] on each concrete sickness record
#   * the CameraAnimation tag on the shared abstract
# The Relic, its quests and its scenes are untouched.
#
# A plain array value REPLACES the vanilla array -- TweakXL's !append / !remove
# insert or drop a single element. So `[]` clears the array and the gameplayTags
# list below is the vanilla list with one entry removed.
"""

# Properties emptied on every concrete sickness record, in emit order.
YAML_EMPTY_FIELDS = ("VFX", "packages")

TAG_RE = re.compile(r"^\s*[\w\[\]<> ,]*\bgameplayTags\s*(\+?=)")


def yaml_tags(body, where, record):
    """Return the quoted entries of a record body's gameplayTags field."""
    start = None
    for idx, raw in enumerate(body):
        if TAG_RE.match(raw):
            start = idx
            break
    if start is None:
        raise SystemExit(f"yaml FAILED [{where}] {record}: no gameplayTags field -- "
                         f"the shipped source changed shape, review before shipping")
    text, depth = "", 0
    for raw in body[start:]:
        text += raw + "\n"
        depth += raw.count("{") - raw.count("}")
        if raw.strip().endswith(";"):
            break
    tags = re.findall(r'"([^"]+)"', text)
    if not tags:
        raise SystemExit(f"yaml FAILED [{where}] {record}: gameplayTags parsed empty")
    return tags


def build_yaml(vanilla_texts):
    """Emit the r6/tweaks overlay from the shipped sources.

    For every target record the emitter writes only the properties the patch
    form would have removed. A field the spec expects but vanilla no longer
    defines is a hard error, so a patch that renames or drops a field fails the
    build instead of shipping a YAML that TweakXL would silently reject.
    """
    out = [YAML_HEADER.rstrip("\n"), ""]
    emitted = 0

    for rel, text in vanilla_texts.items():
        spec = TARGETS[rel]
        lines = text.splitlines()
        bodies = {name: lines[head + 1:tail + 1]
                  for name, _, head, _, tail in split_records(text)}

        for name in spec["strip_tag_from"]:
            tag = spec["strip_tag"]
            tags = yaml_tags(bodies[name], rel, name)
            if tag not in tags:
                raise SystemExit(f"yaml FAILED [{rel}] {name}: tag {tag!r} absent "
                                 f"from gameplayTags {tags}")
            kept = [t for t in tags if t != tag]
            out.append(f"BaseStatusEffect.{name}:")
            out.append(f"  # vanilla gameplayTags: {', '.join(tags)}")
            out.append(f"  gameplayTags: [ {', '.join(kept)} ]")
            out.append("")
            emitted += 1

        for name in spec["emptied"]:
            body = bodies[name]
            missing = [f for f in YAML_EMPTY_FIELDS if field_span(body, f) is None]
            if missing:
                raise SystemExit(f"yaml FAILED [{rel}] {name}: vanilla no longer defines "
                                 f"{missing} -- review before shipping")
            out.append(f"BaseStatusEffect.{name}:")
            for field in YAML_EMPTY_FIELDS:
                out.append(f"  {field}: []")
            out.append("")
            emitted += 1

    if not emitted:
        raise SystemExit("yaml FAILED: nothing emitted -- TARGETS is empty?")
    return "\n".join(out).rstrip("\n") + "\n"


def verify_yaml(vanilla_texts, yaml_text):
    """Check the emitted overlay covers exactly the intended records/properties.

    A tiny structural parser, not a YAML library: the file's shape is fixed, and
    an unexpected shape is itself the thing worth failing on.
    """
    errors = []
    want_empty = {name for spec in TARGETS.values() for name in spec["emptied"]}
    want_removed = {name: spec["strip_tag"]
                    for spec in TARGETS.values() if spec["strip_tag"]
                    for name in spec["strip_tag_from"]}

    records, current = {}, None
    for raw in yaml_text.splitlines():
        m = re.match(r"^BaseStatusEffect\.(\w+):\s*$", raw)
        if m:
            current = m.group(1)
            records.setdefault(current, [])
            continue
        if raw.strip().startswith("#") or not raw.strip():
            continue
        if current is not None:
            records[current].append(raw.strip())

    expected = {name for spec in TARGETS.values()
                for name in list(spec["strip_tag_from"]) + list(spec["emptied"])}
    for name in sorted(expected - set(records)):
        errors.append(f"{name}: not present in the overlay")
    for name in sorted(set(records) - expected):
        errors.append(f"{name}: present in the overlay but not a target")

    for name in sorted(want_empty & set(records)):
        props = records[name]
        for field in YAML_EMPTY_FIELDS:
            if f"{field}: []" not in props:
                errors.append(f"{name}: missing `{field}: []`")

    for name, tag in want_removed.items():
        joined = " ".join(records.get(name, []))
        if "gameplayTags" not in joined:
            errors.append(f"{name}: no gameplayTags override")
        if tag in joined:
            errors.append(f"{name}: still lists the stripped tag {tag!r}")

    return errors


# --------------------------------------------------------------- verifying ---


def verify_file(vanilla_text, override_text, spec, where):
    base, _ = parse(vanilla_text)
    over = parse(override_text)[0]
    targets = list(spec["records"])
    errors = []

    dropped = [n for n in base if n not in over]
    if dropped:
        errors.append(f"{where}: dropped records vanilla defines: {dropped}")

    unknown = [n for n in over if n not in base]
    if unknown:
        errors.append(f"{where}: declares records vanilla does not have: {unknown}")

    for name in targets:
        if name not in over:
            errors.append(f"{where}: missing record {name}")
            continue
        if name in base and over[name][0] != base[name][0]:
            errors.append(f"{where}: {name}: parent changed "
                          f"{base[name][0]} -> {over[name][0]}")
        body = "\n".join(over[name][1])
        for token in FORBIDDEN_IN_TARGET:
            if re.search(rf"\b{re.escape(token)}\b", body):
                errors.append(f"{where}: {name}: still mentions {token!r}")

    for name in base:
        if name in targets or name not in over:
            continue
        if base[name][1] != over[name][1]:
            errors.append(f"{where}: {name}: differs from vanilla but was not a target")

    for name in targets:
        if name in base and name in over and base[name][1] == over[name][1]:
            errors.append(f"{where}: {name}: identical to vanilla -- the edit did nothing")

    return errors


# -------------------------------------------------------------------- cli ----


def main():
    p = argparse.ArgumentParser(description=__doc__,
                                formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = p.add_subparsers(dest="cmd", required=True)

    b = sub.add_parser("build", help="regenerate the overrides from the shipped sources")
    b.add_argument("--vanilla-root", type=pathlib.Path, required=True,
                   help="the game's tools/redmod/tweaks directory")
    b.add_argument("--out-root", type=pathlib.Path, required=True)
    b.add_argument("--diff", action="store_true", help="print a unified diff per file")

    v = sub.add_parser("verify", help="check the overrides' invariants")
    v.add_argument("--vanilla-root", type=pathlib.Path, required=True)
    v.add_argument("--override-root", type=pathlib.Path, required=True)

    y = sub.add_parser("yaml", help="emit the TweakXL r6/tweaks drop-in overlay")
    y.add_argument("--vanilla-root", type=pathlib.Path, required=True)
    y.add_argument("--out", type=pathlib.Path, required=True)

    vy = sub.add_parser("verify-yaml", help="check the drop-in overlay's invariants")
    vy.add_argument("--vanilla-root", type=pathlib.Path, required=True)
    vy.add_argument("--yaml", type=pathlib.Path, required=True)

    args = p.parse_args()
    errors = []
    built = 0

    if args.cmd in ("yaml", "verify-yaml"):
        vanilla_texts = {}
        for rel in TARGETS:
            src = args.vanilla_root / rel
            if not src.is_file():
                errors.append(f"missing shipped source: {src}")
                continue
            vanilla_texts[rel] = src.read_text(encoding="utf-8")
        if errors:
            for e in errors:
                print(e, file=sys.stderr)
            return 1

        if args.cmd == "yaml":
            text = build_yaml(vanilla_texts)
            args.out.parent.mkdir(parents=True, exist_ok=True)
            args.out.write_text(text, encoding="utf-8")
            records = sum(len(list(s["strip_tag_from"]) + list(s["emptied"]))
                          for s in TARGETS.values())
            print(f"wrote {args.out} ({records} record overrides)")
            return 0

        if not args.yaml.is_file():
            print(f"missing overlay: {args.yaml}", file=sys.stderr)
            return 1
        errors += verify_yaml(vanilla_texts, args.yaml.read_text(encoding="utf-8"))
        if errors:
            print("verify-yaml FAILED", file=sys.stderr)
            for e in errors:
                print(f"  - {e}", file=sys.stderr)
            return 1
        print("verify-yaml OK: overlay covers exactly the intended records")
        return 0

    for rel, spec in TARGETS.items():
        src = args.vanilla_root / rel
        if not src.is_file():
            errors.append(f"missing shipped source: {src}")
            continue

        if args.cmd == "build":
            out_path = args.out_root / rel
            out_path.parent.mkdir(parents=True, exist_ok=True)
            out_text = build_file(src.read_text(encoding="utf-8"), spec, rel)
            out_path.write_text(out_text, encoding="utf-8")
            built += 1
            print(f"wrote {rel}")
            if args.diff:
                sys.stdout.writelines(difflib.unified_diff(
                    src.read_text(encoding="utf-8").splitlines(True),
                    out_text.splitlines(True),
                    fromfile=f"vanilla/{rel}", tofile=f"override/{rel}"))
            continue

        dst = args.override_root / rel
        if not dst.is_file():
            errors.append(f"missing override: {dst}")
            continue
        errors += verify_file(src.read_text(encoding="utf-8"),
                              dst.read_text(encoding="utf-8"), spec, rel)

    if args.cmd == "build":
        if errors:
            for e in errors:
                print(e, file=sys.stderr)
            return 1
        print(f"build OK: {built}/{len(TARGETS)} shipped sources rewritten")
        return 0

    if errors:
        print("verify FAILED", file=sys.stderr)
        for e in errors:
            print(f"  - {e}", file=sys.stderr)
        return 1
    total = sum(len(s["records"]) for s in TARGETS.values())
    print(f"verify OK: {total} records across {len(TARGETS)} files neutralised; "
          f"every vanilla record preserved, inheritance intact")
    return 0


if __name__ == "__main__":
    sys.exit(main())